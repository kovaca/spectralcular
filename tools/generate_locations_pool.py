def main() -> None:
    entries = []
    for row in LOCATIONS:
        (loc_id, name, bbox, character, themes,
         windows, cloud, source, notes) = row
        entries.append({
            "id": loc_id,
            "name": name,
            "bbox": list(bbox),
            "landscape_character": character,
            "themes": themes,
            "season_windows": windows,
            "cloud_cover_max": cloud,
            "source": source,
            "status": "approved" if loc_id in APPROVED_IDS else "proposed",
            "notes": notes,
        })

    out_path = Path("config/pool/locations.yaml")
    header = (
        "# Stage-3 locations pool — generated by\n"
        "# tools/generate_locations_pool.py. Edit the LOCATIONS table in\n"
        "# that script and re-run, or edit this YAML directly to drive the\n"
        "# editorial loop (status: proposed → approved | rejected | needs_revision).\n"
        "#\n"
        "# Themes a location plausibly serves are tagged here so the\n"
        "# stage-4 affinity table is a fan-out join, not a re-curation.\n"
        "# A few bboxes intentionally exceed the 26.25 × 33.75 km AOI\n"
        "# ceiling — those will flag in the contact sheet's ceiling\n"
        "# indicator and the reviewer can decide whether the resampled\n"
        "# render is acceptable.\n\n"
    )
    body = yaml.safe_dump(
        {"entries": entries},
        sort_keys=False, allow_unicode=True, default_flow_style=False, width=110,
    )
    out_path.write_text(header + body)
    print(f"Wrote {out_path}: {len(entries)} entries")


if __name__ == "__main__":
    main()
